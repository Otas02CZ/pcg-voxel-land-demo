		if (Input.IsActionJustPressed("toggle_sun"))
		{
			sunMovementEnabled = !sunMovementEnabled;
		}
		
		// update sun position if automatic sun cycle is enabled
		if (sunMovementEnabled)
		{
			UpdateSunPosition(delta);
		}
	}

