	/**
	 * Initializes given world, necessary services and generators to startup world generation.
	 * Firstly model generator is run. After it finishes iterative generation starts.
	 */
	public void StartWorldGeneration(WorldSaveConfig worldSaveConfig, bool newGame)
	{
		// process settings to calculate offsets and dependent parameters
		currentOriginShiftOffsetXZ = new Vector3Int(0, 0, 0);
		WorldSettings settings = worldSaveConfig.worldSettings;
		seed = worldSaveConfig.worldSettings.seed;
		terrainChunkCountY = worldSaveConfig.worldSettings.terrainChunkCountY;
		chunkCountY = (byte)(terrainChunkCountY + chunkCountYExtraSpacing);
		totalVoxelsY = (chunkCountY * chunkVoxelSize);
		int maxTerrainHeightInMeters = terrainChunkCountY * metersPerChunk;
		int maxTerrainHeightInTerrainUnits = maxTerrainHeightInMeters * terrainUnitsPerMeter;
		ushort caveStartYLevelTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.cavesStartTerrainHeightRatio);
		ushort explicitWaterLevelTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.explicitWaterLevelTerrainHeightRatio);
		ushort cavesWaterHeightTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.cavesWaterLevelTerrainHeightRatio);
		// init cave gen helper
		CaveGeneratorHelperParams caveGenHelperParams = new CaveGeneratorHelperParams {
			seed = seed,
			thresholdCaves = settings.cavesSpaceAmount,
			thresholdTunnelNodes = settings.cavesTunnelsChance,
			thresholdEntranceNodes = settings.cavesTunnelEntrancesChance,
			caveStartYLevelTerrainUnits = caveStartYLevelTerrainUnits
		};
		caveGenerationHelper = new CaveGenerationHelper(caveGenHelperParams);
		
		if (newGame)
		{
			// player will be placed at 0,0,0 position in new world
			player.TeleportPlayer(new Vector3Double(0, 0, 0));
			playerNotPlaced = true;
		}
		else
		{
			// or last position in loaded worlds
			player.TeleportPlayer(worldSaveConfig.lastPlayerPosition);
			CheckPlanOriginShift();
			MoveSun();
		}
		
		waitingForFirstMeshedChunk = true; // ui switches to game only after first column geometry is generated
		// initialize tracking collections for iterative region - chunk system
		loadedRegions = [];
		generatedRegions = [];
		loadedColumns = [];
		generatedColumns = [];
		meshedColumns = [];
		columnLods = new Dictionary<(int, int), LodLevel>();
		// initialize voxel storage and cave gen helper
		voxelStorage = new VoxelStorage(metersPerChunk, voxelsPerMeter, chunkCountY);
		WorldGeneratorParams worldGenParams = new WorldGeneratorParams // parameters for world generator
		{
			seed = seed,
			maxTerrainHeightInTerrainUnits = maxTerrainHeightInTerrainUnits,
			voxelsPerMeter = voxelsPerMeter,
			metersPerRegion = metersPerRegion,
			metersPerChunk = metersPerChunk,
			unitsPerMeter = terrainUnitsPerMeter,
			cavesStartYLevelTerrainUnits = caveStartYLevelTerrainUnits,
			cavesEnabled = settings.cavesEnabled,
			caveGenerationHelper = caveGenerationHelper,
			lakeSize = LakeSize.FromLakeSizeType(settings.lakeSize),
			waterAvailEffectStrength = WaterAvailEffectStrength.FromWaterAvailEffectStrengthType(settings.waterAvailabilityStrength),
			heightNoiseConfig = HeightNoiseConfig.FromHeightNoiseConfigType(settings.heightNoiseConfig),
			vegetationChance = VegetationChance.FromOverallVegetationChanceType(settings.overallVegetationChance),
			explicitWaterLevelTerrainUnits = explicitWaterLevelTerrainUnits,
			maxRiverLength = settings.maxRiverLength,
			explicitWaterAvailabilityMax = settings.explicitWaterAvailabilityMaxEffect,
			areaAgeThresholds = settings.areaAgeThresholds,
			areaHeightThresholds =  settings.areaHeightThresholds,
			areaWaterAvailabilityThresholds = settings.areaWaterAvailabilityThresholds,
			waterLilyChance = settings.waterLilyChance,
			waterReedsChance = settings.waterReedsChance,
			snowOccurenceThreshold = settings.snowChance
		};
		// initialize world generator service with world generator
		worldGeneratorService = new WorldGeneratorService(worldServiceThreads, worldGenParams);
		VoxelGeneratorParams voxelGenParams = new VoxelGeneratorParams
		{
			voxelStorage =  voxelStorage,
			worldGeneratorService = worldGeneratorService,
			storageService = storageService,
			caveGenerationHelper = caveGenerationHelper,
			seed = seed,
			metersPerRegion = metersPerRegion,
			metersPerChunk = metersPerChunk,
			voxelsPerMeter = voxelsPerMeter,
			terrainUnitsPerMeter = terrainUnitsPerMeter,
			caveStartYLevelTerrainUnits = caveStartYLevelTerrainUnits,
			cavesWaterHeightTerrainUnits = cavesWaterHeightTerrainUnits,
			cavesEnabled = settings.cavesEnabled,
			stalactiteChance = settings.cavesStalactitesChance,
			waterfallChance = settings.cavesWaterfallChance
		};
		// initialize remaining services
		voxelGeneratorService = new VoxelGeneratorService(voxelServiceThreads, voxelGenParams);
		geometryGeneratorService = new GeometryGeneratorService(voxelStorage, voxelGeneratorService, geometryServiceThreads, lodCount, chunkCountY);
		worldDisplayService = new WorldDisplayService(geometryGeneratorService, chunkCountY, waterMaterial, blockMaterialBasic, blockMaterialVariance, voxelWorld);
		voxelEditService = new VoxelEditService(voxelStorage, storageService, worldDisplayService, voxelsPerMeter, chunkCountY, (byte)chunkVoxelSize);
		// and subscribe to their events
		geometryGeneratorService.SubscribeToVoxelEditService(voxelEditService);
		voxelEditService.SubscribeOnEditFailed(OnEditingProcessed);
		worldGeneratorService.SubscribeOnRegionGenerated(OnRegionGenerated);
		voxelGeneratorService.SubscribeOnChunkColumnGenerated(OnChunkColumnGenerated);
		geometryGeneratorService.SubscribeOnColumnGeometryGenerated(OnChunkColumnMeshed);
		geometryGeneratorService.SubscribeOnEditingProcessed(OnEditingProcessed);
		// init, configure and run model generation
		modelService = new ModelService(seed, modelServiceThreads);
		modelService.SubscribeOnModelsGenerated(OnModelsGenerated);
		VoxelModelDefinitions.InsertVoxelModelDefinitions(modelService);
		menu.ShowCenteredMessageLoading($"Generating models ... (0/{modelService.GetTotalModelsCount()})");
		generatingModels = true;
		modelService.GenerateModels();
	}

	/**
	 * Unloads currently active world by disposing of all data instances of services and generators.
	 */
	private void UnloadWorld()
	{
		// need to stop all generation tasks, disable threads, clear storage and services / generators
		iterativeRuns = false;

		voxelEditService = null;
		
		if (worldDisplayService != null)
		{
			worldDisplayService.Dispose();
			worldDisplayService = null;
		}
		
		if (geometryGeneratorService != null)
		{
			geometryGeneratorService.Dispose();
			geometryGeneratorService = null;
		}
		
		if (voxelGeneratorService != null)
		{
			voxelGeneratorService.Dispose();
			voxelGeneratorService = null;
		}
		
		if (worldGeneratorService != null)
		{
			worldGeneratorService.Dispose();
			worldGeneratorService = null;
		}

		caveGenerationHelper = null;
		
		voxelStorage  = null;
		
		if (worldDisplayService != null)
		{
			worldDisplayService.Dispose();
			worldDisplayService = null;
		}

		storageService.Dispose();

		if (modelService != null)
		{
			modelService.Dispose();
			modelService = null;
		}
	
		loadedRegions = null;
		generatedRegions = null;
		loadedColumns = null;
		generatedColumns = null;
		meshedColumns = null;
		columnLods = null;
	}
	
	/**
	 * Configures LOD distances based on supplied values.
	 * For changes of values from UI and loaded application settings.
	 */
	public void SetLodConfiguration(int distance0, int distance1, int distance2)
	{
		lodDistance0 = distance0;
		lodDistance1 = distance1;
		lodDistance2 = distance2;
		
		CalculateRegionChunksDistances(); // needs to recalculate all dependent distances for the iterative system

		// this part does not execute now, as lod can be configured only outside running game
		// I changed this due to remaining issues of the iterative system that resulted in missing columns
		if (iterativeRuns)
		{
			CalculateRegionsChunksAsync(player.GetRealPosition());
		}
	}

	/**
	 * Recalculates distances for the iterative generation system region - chunk calculation step.
	 */
	private void CalculateRegionChunksDistances()
	{
		lodDistanceMax = lodDistance2;
		regionTerrainTriggerDistance = regionTerrainMin + lodDistanceMax;
		regionFeaturesTriggerDistance = regionFeaturesMin + lodDistanceMax;
		columnPreparationDistance = lodDistanceMax + columnPreparationDistanceAddition;
		columnVoxelizationDistance = lodDistanceMax + columnVoxelizationDistanceAddition;
		columnMeshingDistance = lodDistanceMax + columnMeshingDistanceAddition;

		regionTriggerDistanceUnload = regionTerrainTriggerDistance + regionUnloadMargin;
		columnDistanceUnload = columnPreparationDistance + lodUnloadMargin;
		columnMeshingDistanceUnload = columnMeshingDistance + lodUnloadMargin;
	}

	/**
	 * Starts up asynchronous task that runs CalculateRegionsChunks method.
	 * Only a single task can run at the same time.
	 */
	private void CalculateRegionsChunksAsync(Vector3Double cameraPosition)
	{
		if (calculateRegionsChunksTask != null && !calculateRegionsChunksTask.IsCompleted)
			return;

		calculateRegionsChunksTask = Task.Run(() => CalculateRegionsChunks(cameraPosition));
	}

	/**
	 * Calculates regions and columns that on all levels of the hierarchical system that should be now displayed.
	 * And supplies tasks to all levels of the system to change its state to the new one.
	 */
	private void CalculateRegionsChunks(Vector3Double cameraPosition)
	{
		// regions loading - terrain
		var (camRegionX, camRegionZ) = worldGeneratorService.WorldPosToRegionCoords(cameraPosition.x, cameraPosition.z);
		Vector3Double minPos = cameraPosition - new Vector3Double(regionTerrainTriggerDistance, 0, regionTerrainTriggerDistance);
		Vector3Double maxPos = cameraPosition + new Vector3Double(regionTerrainTriggerDistance, 0, regionTerrainTriggerDistance);
		var (minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		var (maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		// generate tasks if not already present
		for (int regionX = minRegionX; regionX <= maxRegionX; regionX++)
		{
			for (int regionZ = minRegionZ; regionZ <= maxRegionZ; regionZ++)
			{
				if (!loadedRegions.Contains((regionX, regionZ)))
				{
					loadedRegions.Add((regionX, regionZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(regionX - camRegionX) + Math.Abs(regionZ - camRegionZ);
					worldGeneratorService.AddTask(new WorldGenTask(REGION_TASK_TYPE.GENERATE_TERRAIN, regionX, regionZ, priority));
				}
			}
		}
		
		// regions loading - features
		minPos = cameraPosition - new Vector3Double(regionFeaturesTriggerDistance, 0, regionFeaturesTriggerDistance);
		maxPos = cameraPosition + new Vector3Double(regionFeaturesTriggerDistance, 0, regionFeaturesTriggerDistance);
		(minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		(maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		// generate tasks if not already present
		for (int regionX = minRegionX; regionX <= maxRegionX; regionX++)
		{
			for (int regionZ = minRegionZ; regionZ <= maxRegionZ; regionZ++)
			{
				if (!generatedRegions.Contains((regionX, regionZ)))
				{
					generatedRegions.Add((regionX, regionZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(regionX - camRegionX) + Math.Abs(regionZ - camRegionZ);
					worldGeneratorService.AddTask(new WorldGenTask(REGION_TASK_TYPE.GENERATE_FEATURES, regionX, regionZ, priority));
				}
			}
		}
		
		// regions unloading
		minPos = cameraPosition - new Vector3Double(regionTriggerDistanceUnload, 0, regionTriggerDistanceUnload);
		maxPos = cameraPosition + new Vector3Double(regionTriggerDistanceUnload, 0, regionTriggerDistanceUnload);
		(minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		(maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		HashSet<(int x, int z)> regionsToUnload = [];
		// actual region removal happens only on the larger rectangle of loaded regions that only cover the terrain generation phase of regions
		foreach (var (regionX, regionZ) in loadedRegions)
		{
			if (regionX < minRegionX || regionX > maxRegionX || regionZ < minRegionZ || regionZ > maxRegionZ)
			{
				regionsToUnload.Add((regionX, regionZ));
			}
		}
		foreach (var region in regionsToUnload)
		{
			loadedRegions.Remove(region);
			generatedRegions.Remove(region);
			worldGeneratorService.UnloadRegion(region.x, region.z);
		}
		regionsToUnload.Clear();
		
		// chunk columns loading
		minPos = cameraPosition - new Vector3Double(columnPreparationDistance, 0, columnPreparationDistance);
		maxPos = cameraPosition + new Vector3Double(columnPreparationDistance, 0, columnPreparationDistance);
		var (minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		var (maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		// create chunk columns in voxel storage if not present
		for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
		{
			for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
			{
				if (!loadedColumns.Contains((chunkX, chunkZ)))
				{
					loadedColumns.Add((chunkX, chunkZ));
					voxelStorage.CreateChunkColumn(chunkX, chunkZ);
				}
			}
		}
		// chunk columns unloading
		minPos = cameraPosition - new Vector3Double(columnDistanceUnload, 0, columnDistanceUnload);
		maxPos = cameraPosition + new Vector3Double(columnDistanceUnload, 0, columnDistanceUnload);
		(minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		(maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		HashSet<(int x, int z)> columnsToUnload = [];
		// for loaded columns with cleanup of voxel storage
		foreach (var (chunkX, chunkZ) in loadedColumns)
		{
			if (chunkX < minChunkX || chunkX > maxChunkX || chunkZ < minChunkZ || chunkZ > maxChunkZ)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		foreach (var chunk in columnsToUnload)
		{
			loadedColumns.Remove(chunk);
			voxelStorage.RemoveChunkColumn(chunk.x, chunk.z);
			GD.Print($"Unloaded chunk column at {chunk.x}, {chunk.z} from voxel storage");
		}
		// for generated active chunks in voxel generator, needs to be split, otherwise voxel storage would have
		// a set of incorrect canceled tasks and some columns would never be generated
		columnsToUnload.Clear();
		foreach (var (chunkX, chunkZ) in generatedColumns)
		{
			if (chunkX < minChunkX || chunkX > maxChunkX || chunkZ < minChunkZ || chunkZ > maxChunkZ)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		foreach (var chunk in columnsToUnload)
		{
			// remove from generated columns
			generatedColumns.Remove(chunk);
		}
		// voxelization unloading
		voxelGeneratorService.UnloadColumns(columnsToUnload);
		columnsToUnload.Clear();
		
		// voxelization loading
		var (camChunkX, camChunkZ) = voxelStorage.WorldPosToChunkCoords(cameraPosition.x, cameraPosition.z);
		minPos = cameraPosition - new Vector3Double(columnVoxelizationDistance, 0, columnVoxelizationDistance);
		maxPos = cameraPosition + new Vector3Double(columnVoxelizationDistance, 0, columnVoxelizationDistance);
		(minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		(maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		// plan voxelization of not yet voxelized columns
		for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
		{
			for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
			{
				if (!generatedColumns.Contains((chunkX, chunkZ)))
				{
					generatedColumns.Add((chunkX, chunkZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(chunkX - camChunkX) + Math.Abs(chunkZ - camChunkZ);
					voxelGeneratorService.AddTask(new ChunkColumnTask(chunkX, chunkZ, priority));
				}
			}
		}
		
		// geometry unloading
		minPos = cameraPosition - new Vector3Double(columnMeshingDistanceUnload, 0, columnMeshingDistanceUnload);
		maxPos = cameraPosition + new Vector3Double(columnMeshingDistanceUnload, 0, columnMeshingDistanceUnload);
		(minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		(maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		foreach (var (chunkX, chunkZ) in meshedColumns)
		{
			if (chunkX < minChunkX || chunkX > maxChunkX || chunkZ < minChunkZ || chunkZ > maxChunkZ)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		
		foreach (var chunk in columnsToUnload)
		{
			meshedColumns.Remove(chunk);
		}
		// unload geometry in one pass
		geometryGeneratorService.UnloadColumns(columnsToUnload);
		columnsToUnload.Clear();
		
		// geometry loading
		minPos = cameraPosition - new Vector3Double(columnMeshingDistance, 0, columnMeshingDistance);
		maxPos = cameraPosition + new Vector3Double(columnMeshingDistance, 0, columnMeshingDistance);
		(minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		(maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		// plan generation of not yet planned geometry
		for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
		{
			for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
			{
				if (!meshedColumns.Contains((chunkX, chunkZ)))
				{
					meshedColumns.Add((chunkX, chunkZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(chunkX - camChunkX) + Math.Abs(chunkZ - camChunkZ);
					geometryGeneratorService.AddNormalTask(new ChunkColumnGeometryTask(GEOMETRY_TASK_TYPE.GENERATE, chunkX, uint.MaxValue, chunkZ, priority));
				}
			}
		}
		
		// calculate target lods for viewing
		Vector3Double minPosLod2 = cameraPosition - new Vector3Double(lodDistance2, 0, lodDistance2);
		Vector3Double maxPosLod2 = cameraPosition + new Vector3Double(lodDistance2, 0, lodDistance2);
		var (minChunkXLod2, minChunkZLod2) = voxelStorage.WorldPosToChunkCoords(minPosLod2.x, minPosLod2.z);
		var (maxChunkXLod2, maxChunkZLod2) = voxelStorage.WorldPosToChunkCoords(maxPosLod2.x, maxPosLod2.z);
		Vector3Double minPosLod1 = cameraPosition - new Vector3Double(lodDistance1, 0, lodDistance1);
		Vector3Double maxPosLod1 = cameraPosition + new Vector3Double(lodDistance1, 0, lodDistance1);
		var (minChunkXLod1, minChunkZLod1) = voxelStorage.WorldPosToChunkCoords(minPosLod1.x, minPosLod1.z);
		var (maxChunkXLod1, maxChunkZLod1) = voxelStorage.WorldPosToChunkCoords(maxPosLod1.x, maxPosLod1.z);
		Vector3Double minPosLod0 = cameraPosition - new Vector3Double(lodDistance0, 0, lodDistance0);
		Vector3Double maxPosLod0 = cameraPosition + new Vector3Double(lodDistance0, 0, lodDistance0);
		var (minChunkXLod0, minChunkZLod0) = voxelStorage.WorldPosToChunkCoords(minPosLod0.x, minPosLod0.z);
		var (maxChunkXLod0, maxChunkZLod0) = voxelStorage.WorldPosToChunkCoords(maxPosLod0.x, maxPosLod0.z);
		// recalculate the lods for chunk columns
		for (int chunkX = minChunkXLod2; chunkX <= maxChunkXLod2; chunkX++)
		{
			for (int chunkZ = minChunkZLod2; chunkZ <= maxChunkZLod2; chunkZ++)
			{
				// switch to correct lod
				LodLevel correctLod = LodLevel.UNLOADED;
				if (chunkX >= minChunkXLod0 && chunkX <= maxChunkXLod0 && chunkZ >= minChunkZLod0 && chunkZ <= maxChunkZLod0)
				{
					correctLod = LodLevel.LOD0;
				}
				else
				if (chunkX >= minChunkXLod1 && chunkX <= maxChunkXLod1 && chunkZ >= minChunkZLod1 && chunkZ <= maxChunkZLod1)
				{
					correctLod = LodLevel.LOD1;
				}
				else 
				if (chunkX >= minChunkXLod2 && chunkX <= maxChunkXLod2 && chunkZ >= minChunkZLod2 && chunkZ <= maxChunkZLod2)
				{
					correctLod = LodLevel.LOD2;
				}

				// new column to display
				if (!columnLods.ContainsKey((chunkX, chunkZ)))
				{
					columnLods[(chunkX, chunkZ)] = correctLod;
					worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.DISPLAY, chunkX, uint.MaxValue, chunkZ, correctLod));
				}
				else
				{ // updating displayed one
					LodLevel currentLod = columnLods[(chunkX, chunkZ)];
					if (currentLod != correctLod)
					{
						columnLods[(chunkX, chunkZ)] = correctLod;
						worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.DISPLAY, chunkX, uint.MaxValue, chunkZ, correctLod));
					}
				}
			}
		}
		
		// displayed columns unloading
		foreach (var (chunkX, chunkZ) in columnLods.Keys)
		{
			if (chunkX < minChunkXLod2 || chunkX > maxChunkXLod2 || chunkZ < minChunkZLod2 || chunkZ > maxChunkZLod2)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		
		foreach (var column in columnsToUnload)
		{
			columnLods.Remove(column);
			worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.HIDE, column.x, uint.MaxValue, column.z, LodLevel.UNLOADED));
		}
	}
	
