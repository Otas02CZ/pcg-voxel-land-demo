	/**
	 * Periodic engine yielded invocation.
	 * Yields itself to the world display service to apply its pre-processed tasks - display, update and cleanup.
	 * Performs planned origin shift update.
	 * Processes updates to the debug menu, allows toggling of several features (debug menu, wireframe, sun movement).
	 * Triggers voxel editing based on user input and runs the sun movement code.
	 */
	public override void _Process(double delta)
	{
		// show model generation progress
		if (generatingModels)
		{
			uint totalModels = modelService.GetTotalModelsCount();
			uint remainingModels = modelService.GetRemainingTasksCount();
			menu.ShowCenteredMessageLoading($"Generating models... {totalModels - remainingModels}/{totalModels}");
		}

		if (iterativeRuns)
		{
            // column display management
            // hide columns
            worldDisplayService.ProcessPlannedMeshUnloads();
            // process column display and updates
            ProcessCompletedMeshes(delta);
            // perform origin shift when planned
            if (originShiftPlanned)
            {
                PerformOriginShift();
                originShiftPlanned = false;
            }
            // weather simulation
            weatherEnvManager.SimulationStep();
            
			// update debug menu with stats
			var worldGenActiveRegions = worldGeneratorService.GetActiveRegionsCount();
			var worldGenRemainingTasks = worldGeneratorService.GetRemainingTasksCount();
			var worldGenLockedTasks = worldGeneratorService.GetLockedTasksCount();
			var worldGenWorkingTasks = worldGeneratorService.GetActiveThreadsCount();
			var voxelGenActiveColumns = voxelGeneratorService.GetActiveColumnsCount();
			var voxelGenRemainingTasks = voxelGeneratorService.GetRemainingTasksCount();
			var voxelGenLockedTasks = voxelGeneratorService.GetLockedTasksCount();
			var voxelGenWaitingNeighborsCount = voxelGeneratorService.GetWaitingNeighborsCount();
			var modelGenRemainingTasks = modelService.GetRemainingTasksCount();
			var geometryGenRemainingTasks = geometryGeneratorService.GetRemainingTasksCount();
			var geometryGenLockedTasks = geometryGeneratorService.GetLockedTasksCount();
			var geometryGenActiveColumns = geometryGeneratorService.GetActiveColumnsCount();
            List<long> lodResults = geometryGeneratorService.GetAverageChunkLodGenerationTime();
			var meshViewDisplayedColumns = worldDisplayService.GetDisplayedColumnsCount();
			var meshViewRemainingTasks = worldDisplayService.GetRemainingTasksCount();
			var meshViewLockedTasks = worldDisplayService.GetLockedTasksCount();
			Vector3Double realPlayerPosition = player.GetRealPosition();
			var cameraChunk = new Vector3Int(
				(int)Math.Floor(realPlayerPosition.x / metersPerChunk),
				(int)Math.Floor(realPlayerPosition.y / metersPerChunk),
				(int)Math.Floor(realPlayerPosition.z / metersPerChunk)
			);
			Vector3 shiftedPlayerPosition = player.Position;

			fpsLabel.Text = $"WORLD GEN (A/W/R/L): {worldGenActiveRegions}/{worldGenWorkingTasks}/{worldGenRemainingTasks}/{worldGenLockedTasks}\n" +
							$"VOXEL GEN (A/R/L): {voxelGenActiveColumns}/{voxelGenRemainingTasks}/{voxelGenLockedTasks}/{voxelGenWaitingNeighborsCount}\n" +
							$"GEOMT GEN (A/R/L): {geometryGenActiveColumns}/{geometryGenRemainingTasks}/{geometryGenLockedTasks}\n" +
							$"MESH  GEN: {lodResults[0]}/{lodResults[1]}/{lodResults[2]}/{lodResults[3]} ms average\n" +
							$"MESH VIEW (A/R/L): {meshViewDisplayedColumns}/{meshViewRemainingTasks}/{meshViewLockedTasks}\n" +
							$"MODEL GEN (R): {modelGenRemainingTasks}\n" +
							$"CAMERA CHUNK: {cameraChunk.x}, {cameraChunk.y}, {cameraChunk.z}\n" +
							$"CAMERA POSITION: {Math.Round(realPlayerPosition.x, 2)}, {Math.Round(realPlayerPosition.y, 2)}, {Math.Round(realPlayerPosition.z, 2)}\n" +
							$"ORIGIN SHIFT OFFSET: {currentOriginShiftOffsetXZ.x}, {currentOriginShiftOffsetXZ.z}\n" +
							$"SHIFTED CAMERA POSITION: {Math.Round(shiftedPlayerPosition.X, 2)}, {Math.Round(shiftedPlayerPosition.Y, 2)}, {Math.Round(shiftedPlayerPosition.Z, 2)}";

            // toggle sun automatic cycle
            if (Input.IsActionJustPressed("toggle_sun"))
            {
                weatherEnvManager.SetDayCycleStatus(!weatherEnvManager.dayCycleEnabled);
                menu.UpdateInGameDayCycleState(weatherEnvManager.dayCycleEnabled);
            }
            // toggle weather simulation
            if (Input.IsActionJustPressed("toggle_weather"))
            {
                weatherEnvManager.SetWeatherSimulationStatus(!weatherEnvManager.weatherCycleEnabled);
                menu.UpdateInGameWeatherSimulationState(weatherEnvManager.weatherCycleEnabled);
            }
		}
		// toggle debug menu
		if (Input.IsActionJustPressed("debug_menu"))
		{
			fpsLabel.SetVisible(!fpsLabel.Visible);
		}
		// toggle wireframe display
		if (Input.IsActionJustPressed("toggle_wireframe"))
		{
			switch (displayMode)
			{
				case DisplayMode.DEFAULT:
					GetViewport().DebugDraw = Viewport.DebugDrawEnum.Wireframe;
					displayMode = DisplayMode.WIREFRAME;
					break;
				case DisplayMode.WIREFRAME:
					GetViewport().DebugDraw = Viewport.DebugDrawEnum.Disabled;
					displayMode = DisplayMode.DEFAULT;
					break;
			}
		}
		
		// block placement and removal
		if (editingEnabled)
		{
			if (Input.IsActionJustReleased("destroy_block"))
			{
				Vector3 lookAtDirection = player.GetLookAtDirection();
				Vector3Double playerPosition = player.GetCenteredCameraRealPosition();
				
				// block destruction - async
				editingEnabled = false;
				voxelEditService.RaycastVoxelEditAsync(playerPosition, lookAtDirection, maxEditingDistance, editingVoxelType, editingVoxelSize, false);
			}
			else if (Input.IsActionJustReleased("place_block"))
			{
				Vector3 lookAtDirection = player.GetLookAtDirection();
				Vector3Double playerPosition = player.GetCenteredCameraRealPosition();
				
				// block placement - async
				editingEnabled = false;
				voxelEditService.RaycastVoxelEditAsync(playerPosition, lookAtDirection, maxEditingDistance, editingVoxelType, editingVoxelSize, true);
			}
		}
	}

