		// init, configure and run model generation
		modelService = new ModelService(seed, modelServiceThreads);
		modelService.SubscribeOnModelsGenerated(OnModelsGenerated);
		VoxelModelDefinitions.InsertVoxelModelDefinitions(modelService);
		menu.ShowCenteredMessageLoading($"Generating models ... (0/{modelService.GetTotalModelsCount()})");
		generatingModels = true;
		modelService.GenerateModels();
        weatherEnvManager.Start(worldGeneratorService, worldSaveConfig.worldSettings.seed, worldSaveConfig.sunAngle, worldSaveConfig.weatherSimulationTime);
        player.SetTorchVisibility(worldSaveConfig.torchEnabled);
        
        // player placing and positioning
        if (newGame)
        {
            // player will be placed at 0,0,0 position in new world
            player.TeleportPlayer(new Vector3Double(0, 0, 0));
            playerNotPlaced = true;
        }
        else
        {
            // or last position in loaded worlds
            player.TeleportPlayer(worldSaveConfig.lastPlayerPosition);
            weatherEnvManager.OnPlayerPositionChanged();
            CheckPlanOriginShift();
            weatherEnvManager.MoveLights();
        }
	}

	/**
	 * Unloads currently active world by disposing of all data instances of services and generators.
	 */
	private void UnloadWorld()
	{
		// need to stop all generation tasks, disable threads, clear storage and services / generators
		iterativeRuns = false;

        weatherEnvManager.Stop();
        
		voxelEditService = null;
		
		if (worldDisplayService != null)
		{
			worldDisplayService.Dispose();
			worldDisplayService = null;
		}
		
		if (geometryGeneratorService != null)
		{
			geometryGeneratorService.Dispose();
			geometryGeneratorService = null;
		}
		
		if (voxelGeneratorService != null)
		{
			voxelGeneratorService.Dispose();
			voxelGeneratorService = null;
		}
		
		if (worldGeneratorService != null)
		{
			worldGeneratorService.Dispose();
			worldGeneratorService = null;
		}

		caveGenerationHelper = null;
		
		voxelStorage  = null;
		
		if (worldDisplayService != null)
		{
			worldDisplayService.Dispose();
			worldDisplayService = null;
		}

		storageService.Dispose();

		if (modelService != null)
		{
			modelService.Dispose();
			modelService = null;
		}
	
		loadedRegions = null;
		generatedRegions = null;
		loadedColumns = null;
		generatedColumns = null;
        meshedColumnLods[0] = null;
        meshedColumnLods[1] = null;
        meshedColumnLods[2] = null;
        meshedColumnLods[3] = null;
		columnLods = null;
		
		GC.Collect();
	}
	
	/**
	 * Configures LOD distances based on supplied values.
	 * For changes of values from UI and loaded application settings.
	 */
	public void SetLodConfiguration(int[] distances)
	{
        if (lodDistances == null || lodDistances.Length != lodCount)
        {
            GD.PrintErr("Incorrect number of lod distances");
        }
        
        lodDistances = distances;
		
		CalculateRegionChunksDistances(); // needs to recalculate all dependent distances for the iterative system
        
		if (iterativeRuns)
		{
			CalculateRegionsChunksAsync(player.GetRealPosition());
		}
	}

	/**
	 * Recalculates distances for the iterative generation system region - chunk calculation step.
	 * Includes calculation of squared values of chunk system distances for later circular chunk system checks.
	 */
	private void CalculateRegionChunksDistances()
	{
		lodDistanceMax = lodDistances[lodCount-1];
		regionTerrainTriggerDistance = regionTerrainMin + lodDistanceMax;
		regionFeaturesTriggerDistance = regionFeaturesMin + lodDistanceMax;
		columnPreparationDistance = lodDistanceMax + columnPreparationDistanceAddition;
		columnVoxelizationDistance = lodDistanceMax + columnVoxelizationDistanceAddition;
		regionTriggerDistanceUnload = regionTerrainTriggerDistance + regionUnloadMargin;
		columnStorageDistanceUnload = columnPreparationDistance + columnStorageUnloadMargin;
        columnGeneratorDistCancel = columnVoxelizationDistance + columnGeneratorCancelMargin;
		// squared distances in chunk units for circular chunk system recalculation
		columnPrepDistSquared = (int)Math.Pow(columnPreparationDistance/(double)metersPerChunk, 2);
		columnStorageDistUnloadSquared = (int)Math.Pow(columnStorageDistanceUnload/(double)metersPerChunk, 2);
		columnVoxDistSquared = (int)Math.Pow(columnVoxelizationDistance/(double)metersPerChunk, 2);
        columnGeneratorDistCancelSquared = (int)Math.Pow(columnGeneratorDistCancel/(double)metersPerChunk, 2);
		
		for (int lod = 0; lod < lodCount; lod++)
		{
			lodDistSquared[lod] = (int)Math.Pow(lodDistances[lod]/(double)metersPerChunk, 2);
			columnMeshingLodDistances[lod] = lodDistances[lod] + columnMeshingDistanceAddition;
			columnMeshingLodDistSquared[lod] = (int)Math.Pow(columnMeshingLodDistances[lod]/(double)metersPerChunk, 2);
			// unload
			columnMeshingLodUnloadDistances[lod] = columnMeshingLodDistances[lod] + columnGeometryUnloadMargin;
			columnMeshingLodUnloadDistSquared[lod] = (int)Math.Pow(columnMeshingLodUnloadDistances[lod]/(double)metersPerChunk, 2);
		}
	}

	/**
	 * Starts up asynchronous task that runs CalculateRegionsChunks method.
	 * Only a single task can run at the same time.
	 */
	private void CalculateRegionsChunksAsync(Vector3Double cameraPosition)
	{
		if (calculateRegionsChunksTask != null && !calculateRegionsChunksTask.IsCompleted)
			return;

		calculateRegionsChunksTask = Task.Run(() => CalculateRegionsChunks(cameraPosition));
	}

	/**
	 * Calculates regions and columns that on all levels of the hierarchical system should be now displayed.
	 * And supplies tasks to all levels of the system to change its state to the new one.
	 * Works with centered circular areas (apart from terrain which still uses rectangles).
	 */
	private void CalculateRegionsChunks(Vector3Double cameraPosition)
	{
		// terrain still rectangular
		// regions loading - terrain
		var (camRegionX, camRegionZ) = worldGeneratorService.WorldPosToRegionCoords(cameraPosition.x, cameraPosition.z);
		Vector3Double minPos = cameraPosition - new Vector3Double(regionTerrainTriggerDistance, 0, regionTerrainTriggerDistance);
		Vector3Double maxPos = cameraPosition + new Vector3Double(regionTerrainTriggerDistance, 0, regionTerrainTriggerDistance);
		var (minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		var (maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		// generate tasks if not already present
		for (int regionX = minRegionX; regionX <= maxRegionX; regionX++)
		{
			for (int regionZ = minRegionZ; regionZ <= maxRegionZ; regionZ++)
			{
				if (!loadedRegions.Contains((regionX, regionZ)))
				{
					loadedRegions.Add((regionX, regionZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(regionX - camRegionX) + Math.Abs(regionZ - camRegionZ);
					worldGeneratorService.AddTask(new WorldGenTask(REGION_TASK_TYPE.GENERATE_TERRAIN, regionX, regionZ, priority));
				}
			}
		}
		
		// regions loading - features
		minPos = cameraPosition - new Vector3Double(regionFeaturesTriggerDistance, 0, regionFeaturesTriggerDistance);
		maxPos = cameraPosition + new Vector3Double(regionFeaturesTriggerDistance, 0, regionFeaturesTriggerDistance);
		(minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		(maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		// generate tasks if not already present
		for (int regionX = minRegionX; regionX <= maxRegionX; regionX++)
		{
			for (int regionZ = minRegionZ; regionZ <= maxRegionZ; regionZ++)
			{
				if (!generatedRegions.Contains((regionX, regionZ)))
				{
					generatedRegions.Add((regionX, regionZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(regionX - camRegionX) + Math.Abs(regionZ - camRegionZ);
					worldGeneratorService.AddTask(new WorldGenTask(REGION_TASK_TYPE.GENERATE_FEATURES, regionX, regionZ, priority));
				}
			}
		}
		
		// regions unloading
		minPos = cameraPosition - new Vector3Double(regionTriggerDistanceUnload, 0, regionTriggerDistanceUnload);
		maxPos = cameraPosition + new Vector3Double(regionTriggerDistanceUnload, 0, regionTriggerDistanceUnload);
		(minRegionX, minRegionZ) = worldGeneratorService.WorldPosToRegionCoords(minPos.x, minPos.z);
		(maxRegionX, maxRegionZ) = worldGeneratorService.WorldPosToRegionCoords(maxPos.x, maxPos.z);
		HashSet<(int x, int z)> regionsToUnload = [];
		// actual region removal happens only on the larger rectangle of loaded regions that only cover the terrain generation phase of regions
		foreach (var (regionX, regionZ) in loadedRegions)
		{
			if (regionX < minRegionX || regionX > maxRegionX || regionZ < minRegionZ || regionZ > maxRegionZ)
			{
				regionsToUnload.Add((regionX, regionZ));
			}
		}
		foreach (var region in regionsToUnload)
		{
			loadedRegions.Remove(region);
			generatedRegions.Remove(region);
			worldGeneratorService.UnloadRegion(region.x, region.z);
		}
		regionsToUnload.Clear();
		
		// chunk columns loading
		var (camChunkX, camChunkZ) = voxelStorage.WorldPosToChunkCoords(cameraPosition.x, cameraPosition.z);
		minPos = cameraPosition - new Vector3Double(columnPreparationDistance, 0, columnPreparationDistance);
		maxPos = cameraPosition + new Vector3Double(columnPreparationDistance, 0, columnPreparationDistance);
		var (minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		var (maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		// create chunk columns in voxel storage if not present
		for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
		{
			for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
			{
				if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) <= columnPrepDistSquared &&
				    !loadedColumns.Contains((chunkX, chunkZ)))
				{
					loadedColumns.Add((chunkX, chunkZ));
					voxelStorage.CreateChunkColumn(chunkX, chunkZ);
				}
			}
		}
		// chunk columns unloading
		HashSet<(int x, int z)> columnsToUnload = [];
		// for loaded columns with cleanup of voxel storage
		foreach (var (chunkX, chunkZ) in loadedColumns)
		{
			if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) > columnStorageDistUnloadSquared)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		foreach (var chunk in columnsToUnload)
		{
			loadedColumns.Remove(chunk);
			voxelStorage.RemoveChunkColumn(chunk.x, chunk.z);
			GD.Print($"Unloaded chunk column at {chunk.x}, {chunk.z} from voxel storage");
		}
        
        // voxelization unloading
		// for generated active chunks in voxel generator, needs to be split, otherwise voxel storage would have
		// a set of incorrect canceled tasks and some columns would never be generated
        columnsToUnload.Clear();
		foreach (var (chunkX, chunkZ) in generatedColumns)
		{
			if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) > columnGeneratorDistCancelSquared)
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		foreach (var chunk in columnsToUnload)
		{
			// remove from generated columns
			generatedColumns.Remove(chunk);
		}
		voxelGeneratorService.UnloadColumns(columnsToUnload);
		columnsToUnload.Clear();
		
		// voxelization loading
		minPos = cameraPosition - new Vector3Double(columnVoxelizationDistance, 0, columnVoxelizationDistance);
		maxPos = cameraPosition + new Vector3Double(columnVoxelizationDistance, 0, columnVoxelizationDistance);
		(minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
		(maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
		// plan voxelization of not yet voxelized columns
		for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
		{
			for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
			{
				if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) <= columnVoxDistSquared &&
				    !generatedColumns.Contains((chunkX, chunkZ)))
				{
					generatedColumns.Add((chunkX, chunkZ));
					// calculate priority with manhattan distance
					int priority = Math.Abs(chunkX - camChunkX) + Math.Abs(chunkZ - camChunkZ);
					voxelGeneratorService.AddTask(new ChunkColumnTask(chunkX, chunkZ, priority));
				}
			}
		}
        
        // geometry unloading
        for (int lod = 0; lod < lodCount; lod++)
        {
            foreach (var (chunkX, chunkZ) in meshedColumnLods[lod])
            {
	            if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) > columnMeshingLodUnloadDistSquared[lod])
                {
                    columnsToUnload.Add((chunkX, chunkZ));
                }
            }
		
            foreach (var chunk in columnsToUnload)
            {
                meshedColumnLods[lod].Remove(chunk);
            }
            // unload geometry in one pass
            geometryGeneratorService.UnloadColumns(columnsToUnload, (LodLevel)lod);
            columnsToUnload.Clear();
        }
		
        // geometry loading
        for (int lod = 0; lod < lodCount; lod++)
        {
            minPos = cameraPosition - new Vector3Double(columnMeshingLodDistances[lod], 0, columnMeshingLodDistances[lod]);
            maxPos = cameraPosition + new Vector3Double(columnMeshingLodDistances[lod], 0, columnMeshingLodDistances[lod]);
            (minChunkX, minChunkZ) = voxelStorage.WorldPosToChunkCoords(minPos.x, minPos.z);
            (maxChunkX, maxChunkZ) = voxelStorage.WorldPosToChunkCoords(maxPos.x, maxPos.z);
            // plan generation of not yet planned geometry
            for (int chunkX = minChunkX; chunkX <= maxChunkX; chunkX++)
            {
                for (int chunkZ = minChunkZ; chunkZ <= maxChunkZ; chunkZ++)
                {
	                if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) <= columnMeshingLodDistSquared[lod] &&
	                    !meshedColumnLods[lod].Contains((chunkX, chunkZ)))
                    {
                        meshedColumnLods[lod].Add((chunkX, chunkZ));
                        // calculate priority with manhattan distance
                        int priority = Math.Abs(chunkX - camChunkX) + Math.Abs(chunkZ - camChunkZ);
                        geometryGeneratorService.AddNormalTask(new ChunkColumnGeometryTask(GEOMETRY_TASK_TYPE.GENERATE, (LodLevel)lod, chunkX, uint.MaxValue, chunkZ, priority));
                    }
                }
            }
        }
        
		// calculate target lods for viewing
        Vector3Double minPosLod3 = cameraPosition - new Vector3Double(lodDistances[3], 0, lodDistances[3]);
        Vector3Double maxPosLod3 = cameraPosition + new Vector3Double(lodDistances[3], 0, lodDistances[3]);
        var (minChunkXLod3, minChunkZLod3) = voxelStorage.WorldPosToChunkCoords(minPosLod3.x, minPosLod3.z);
        var (maxChunkXLod3, maxChunkZLod3) = voxelStorage.WorldPosToChunkCoords(maxPosLod3.x, maxPosLod3.z);
		// recalculate the lods for chunk columns
		for (int chunkX = minChunkXLod3; chunkX <= maxChunkXLod3; chunkX++)
		{
			for (int chunkZ = minChunkZLod3; chunkZ <= maxChunkZLod3; chunkZ++)
			{
				// switch to correct lod
				LodLevel correctLod = LodLevel.UNLOADED;
				double totalDistSquared = Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2);
				// is in circular area
				if (totalDistSquared > lodDistSquared[3])
				{
					continue;
				}
				
				if (totalDistSquared <= lodDistSquared[0])
				{
					correctLod = LodLevel.LOD0;
				}
				else
				if (totalDistSquared <= lodDistSquared[1])
				{
					correctLod = LodLevel.LOD1;
				}
				else
				if (totalDistSquared <= lodDistSquared[2])
				{
					correctLod = LodLevel.LOD2;
				}
				else
				if (totalDistSquared <= lodDistSquared[3])
				{
					correctLod = LodLevel.LOD3;
				}

				// new column to display
				if (!columnLods.ContainsKey((chunkX, chunkZ)))
				{
					columnLods[(chunkX, chunkZ)] = correctLod;
					worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.DISPLAY, chunkX, uint.MaxValue, chunkZ, correctLod));
				}
				else
				{ // updating displayed one
					LodLevel currentLod = columnLods[(chunkX, chunkZ)];
					if (currentLod != correctLod)
					{
						columnLods[(chunkX, chunkZ)] = correctLod;
						worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.DISPLAY, chunkX, uint.MaxValue, chunkZ, correctLod));
					}
				}
			}
		}
		
		// displayed columns unloading
		foreach (var (chunkX, chunkZ) in columnLods.Keys)
		{
			if (Math.Pow(chunkX - camChunkX, 2) + Math.Pow(chunkZ - camChunkZ, 2) > lodDistSquared[3])
			{
				columnsToUnload.Add((chunkX, chunkZ));
			}
		}
		
		foreach (var column in columnsToUnload)
		{
			columnLods.Remove(column);
			worldDisplayService.AddTask(new WorldDisplayTask(WorldDisplayTaskType.HIDE, column.x, uint.MaxValue, column.z, LodLevel.UNLOADED));
		}
	}
	
	/**
	 * Yields current thread to world display service to apply pre-processed DISPLAY / UPDATE tasks.
	 * The amount of applied tasks depends on the current frame time, reducing stuttering.
	 */
	private void ProcessCompletedMeshes(double delta)
	{
        Stopwatch stopwatch = Stopwatch.StartNew();
        while (true)
        {
            worldDisplayService.ProcessDisplayUpdateTask();
            if (stopwatch.ElapsedMilliseconds >= delta * 1000 / chunkUpdatesDeltaDivider)
            {
                break;
            }
        }
	}
	
	/**
	 * Fired when player camera changes position.
	 * Repositions sun based on player position, if it is not in automatic sun cycle.
	 * Starts up region - chunk recalculation and check for origin shift process with debouncing.
	 */
	private void OnCameraPositionChanged()
	{
		if (!iterativeRuns)
			return;
		
		// this debounce is not as necessary now, when only a single async thread can run the calculation at once
		double currentTime = Time.GetUnixTimeFromSystem();
		if (currentTime - lastLodUpdateTime < lodUpdateInterval)
			return;
		
		lastLodUpdateTime = currentTime;
		Vector3Double playerPosition = player.GetRealPosition();
		CalculateRegionsChunksAsync(playerPosition);
		
		CheckPlanOriginShift();
	}
	
	/**
	 * Performs origin shift change with the precomputed offset vector.
	 */
	private void PerformOriginShift()
	{
		// needs to freeze player, move the world and then unfreeze the player
		player.FreezeBeforeOriginShift();
		worldDisplayService.ApplyOriginShift(currentOriginShiftOffsetXZ);
		player.ApplyOriginShift(currentOriginShiftOffsetXZ);
		player.UnfreezeAfterOriginShift();
	}
	
	/**
	 * Checks whether the origin shift vector should change based on different position of player/camera.
	 * Shifting is done on a centered XZ grid of cells. When player moves across cell borders, a different
	 * shift vector is computed so that the whole world and the player would always be placed around the center
	 * of engine coordinate system to reduce floating point precision errors during rendering and physics.
	 * The cell with offset 0,0 is at -halfCell to halfCell area in both X and Z dimension.
	 */
	private void CheckPlanOriginShift()
	{
		if (originShiftPlanned)
			return;
		
		Vector3Double playerPosition = player.GetRealPosition();

		// calculate current cell coordinates of the player
		int cellX = (int)Math.Floor((playerPosition.x + originShiftHalfCell) / originShiftGridCellSize);
		int cellZ = (int)Math.Floor((playerPosition.z + originShiftHalfCell) / originShiftGridCellSize);

		// new origin offset
		int newOffsetX = - cellX * originShiftGridCellSize;
		int newOffsetZ = - cellZ * originShiftGridCellSize;

		// trigger shift, when cells differ
		if (newOffsetX == currentOriginShiftOffsetXZ.x && newOffsetZ == currentOriginShiftOffsetXZ.z)
			return;

		Vector3Int newOriginShift = new Vector3Int(newOffsetX, 0, newOffsetZ);
		currentOriginShiftOffsetXZ = newOriginShift;
		originShiftPlanned = true;
	}

	/**
	 * Teleports player to specified real (non-shifted) position
	 */
	public void TeleportPlayer(Vector3Double realPosition)
	{
		if (!iterativeRuns)
			return;
		
		// reset to bogus value to always trigger a shift offset recalculation
		currentOriginShiftOffsetXZ = new Vector3Int(int.MaxValue, int.MaxValue, int.MaxValue);
		player.TeleportPlayer(realPosition);
		originShiftPlanned = false;
		CheckPlanOriginShift();
		// necessary to recalculate active regions - chunks
		CalculateRegionsChunksAsync(realPosition);
	}
	
