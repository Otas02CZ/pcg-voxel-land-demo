	/**
	 * Processes information that given region was generated by WorldGeneratorService.
	 * Places player and repositions sun, if it was not yet placed and 0,0 region was currently generated
	 */
	private void OnRegionGenerated(WorldRegion region)
	{
		if (playerNotPlaced && region.posX == 0 && region.posZ == 0)
		{
			// place the player if initial position region was generated
			ushort height = region.GetHeightAtLocalCoords(0, 0);
			Vector3Double playerPosition = new Vector3Double(0, (height / terrainUnitsPerMeter) + 2, 0);
			player.CallDeferred(Player.MethodName.TeleportPlayer, playerPosition.x, playerPosition.y, playerPosition.z);
			playerNotPlaced = false;
			// reposition sun based on initial player position
			CallDeferred(MethodName.MoveLightsInWeatherManager);
            // reset player pos in weather manager
            CallDeferred(MethodName.PassPlayerPosChangeToWeatherManager);
        }
		GD.Print($"World region generated at {region.posX}, {region.posZ}");
	}

    /**
     * Dirty way to use call deferred on non-godot class objects.
     * Called from OnRegionGenerated.
