	/**
	 * Initializes given world, necessary services and generators to startup world generation.
	 * Firstly model generator is run. After it finishes iterative generation starts.
	 */
	public void StartWorldGeneration(WorldSaveConfig worldSaveConfig, bool newGame)
	{
		// process settings to calculate offsets and dependent parameters
		currentOriginShiftOffsetXZ = new Vector3Int(0, 0, 0);
		WorldSettings settings = worldSaveConfig.worldSettings;
		seed = worldSaveConfig.worldSettings.seed;
		terrainChunkCountY = worldSaveConfig.worldSettings.terrainChunkCountY;
		chunkCountY = (byte)(terrainChunkCountY + chunkCountYExtraSpacing);
		totalVoxelsY = (chunkCountY * chunkVoxelSize);
		int maxTerrainHeightInMeters = terrainChunkCountY * metersPerChunk;
		int maxTerrainHeightInTerrainUnits = maxTerrainHeightInMeters * terrainUnitsPerMeter;
		ushort caveStartYLevelTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.cavesStartTerrainHeightRatio);
		ushort explicitWaterLevelTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.explicitWaterLevelTerrainHeightRatio);
		ushort cavesWaterHeightTerrainUnits = (ushort)(maxTerrainHeightInTerrainUnits * settings.cavesWaterLevelTerrainHeightRatio);
		// init cave gen helper
		CaveGeneratorHelperParams caveGenHelperParams = new CaveGeneratorHelperParams {
			seed = seed,
			thresholdCaves = settings.cavesSpaceAmount,
			thresholdTunnelNodes = settings.cavesTunnelsChance,
			thresholdEntranceNodes = settings.cavesTunnelEntrancesChance,
			caveStartYLevelTerrainUnits = caveStartYLevelTerrainUnits
		};
		caveGenerationHelper = new CaveGenerationHelper(caveGenHelperParams);
		
		waitingForFirstMeshedChunk = true; // ui switches to game only after first column geometry is generated
		// initialize tracking collections for iterative region - chunk system
		loadedRegions = [];
		generatedRegions = [];
		loadedColumns = [];
		generatedColumns = [];
        meshedColumnLods[0] = [];
        meshedColumnLods[1] = [];
        meshedColumnLods[2] = [];
        meshedColumnLods[3] = [];
		columnLods = new Dictionary<(int, int), LodLevel>();
		// initialize voxel storage and cave gen helper
		voxelStorage = new VoxelStorage(metersPerChunk, voxelsPerMeter, chunkCountY);
		WorldGeneratorParams worldGenParams = new WorldGeneratorParams // parameters for world generator
		{
			seed = seed,
			maxTerrainHeightInTerrainUnits = maxTerrainHeightInTerrainUnits,
			voxelsPerMeter = voxelsPerMeter,
			metersPerRegion = metersPerRegion,
			metersPerChunk = metersPerChunk,
			unitsPerMeter = terrainUnitsPerMeter,
			cavesStartYLevelTerrainUnits = caveStartYLevelTerrainUnits,
			cavesEnabled = settings.cavesEnabled,
			caveGenerationHelper = caveGenerationHelper,
			lakeSize = LakeSize.FromLakeSizeType(settings.lakeSize),
			waterAvailEffectStrength = WaterAvailEffectStrength.FromWaterAvailEffectStrengthType(settings.waterAvailabilityStrength),
			heightNoiseConfig = HeightNoiseConfig.FromHeightNoiseConfigType(settings.heightNoiseConfig),
			vegetationChance = VegetationChance.FromOverallVegetationChanceType(settings.overallVegetationChance),
			explicitWaterLevelTerrainUnits = explicitWaterLevelTerrainUnits,
			maxRiverLength = settings.maxRiverLength,
			explicitWaterAvailabilityMax = settings.explicitWaterAvailabilityMaxEffect,
			areaAgeThresholds = settings.areaAgeThresholds,
			areaHeightThresholds =  settings.areaHeightThresholds,
			areaWaterAvailabilityThresholds = settings.areaWaterAvailabilityThresholds,
			waterLilyChance = settings.waterLilyChance,
			waterReedsChance = settings.waterReedsChance,
			snowOccurenceThreshold = settings.snowChance
		};
		// initialize world generator service with world generator
		worldGeneratorService = new WorldGeneratorService(worldServiceThreads, worldGenParams);
		VoxelGeneratorParams voxelGenParams = new VoxelGeneratorParams
		{
			voxelStorage =  voxelStorage,
			worldGeneratorService = worldGeneratorService,
			storageService = storageService,
			caveGenerationHelper = caveGenerationHelper,
			seed = seed,
			metersPerRegion = metersPerRegion,
