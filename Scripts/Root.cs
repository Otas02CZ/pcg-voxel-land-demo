/*
WORLD GENERATION - DISPLAY SYSTEM
- World divided into chunked areas on multiple levels
	- large regions that mostly contain simple 2D representations of the generated world
	- columns of symmetrical vertically stacked chunks
		- for voxel representation of the generated world, allowing user editing, underground
		- for geometry that is generated from voxels
		- for storing edited voxel data to disk
- Root manages which of these regions and columns of chunks should be currently loaded or displayed
	- uses current player/camera position around which centered circular areas are computed for each level
	of the hierarchical system based on configured distances
	- these circular areas are mapped to a 2D grid of regions and columns
	- differences from the previous state to the new mapping result in creation of tasks for each level
	of the hierarchical system - generate, update, unload and display tasks
- these tasks are then processed by services at their level in the system. Tasks at higher levels are waiting
for their dependencies at lower ones (ex. voxelization of a column waits until the region in which it belongs
is generated by the lower level)
- user voxel editing works partially independently on the main scheduling system. Directly causing update tasks
on geometry level that trigger re-display of given chunks at world display level. Voxel edit operations are also
stored to disk by storage service.
- voxel storage stores all voxelized columns and is managed by root itself, generators and services only fill or use its structures

GENERATION AND DISPLAY HIERARCHY (bottom-up)
WorldDisplayService uses ChunkColumnGeometry
|	- applies geometry to the engine for display
|
GeometryGeneratorService uses GeometryGenerator, internal data in ChunkColumnGeometry structures
|	- generates geometry for voxel representation on column basis
|
VoxelGeneratorService uses VoxelGenerator internal data in ChunkColumns of VoxelStorage
|	- voxelizes region representation into voxel representation on column basis
|
WorldGeneratorService uses WorldGenerator and internal data are in WorldRegions
	- large regions of world parameters - generated height map, placements of features, water, etc.

EDITING HIERARCHY (bottom-up)
WorldDisplayService replaces affected chunks with new geometry
|
GeometryGeneratorService regenerates geometry for affected chunks, triggers re-display, enables voxel editing
|
VoxelEditService raycasts to voxel storage and edits the voxels, triggers chunk geometry regeneration
|	-> StorageService saves resulting voxel operations
Root catches editing events, triggers raycast in VoxelEditService, disables voxel editing, until it is finished
*/


